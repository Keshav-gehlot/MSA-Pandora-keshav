import { describe, expect, it } from "vitest";
import { attributionProblems } from "./check-commit-message.mjs";

describe("attributionProblems", () => {
  it("accepts a plain message", () => {
    expect(attributionProblems("Add the registration form\n\nValidates the team size on the server.\n")).toEqual([]);
  });

  it("rejects a Co-Authored-By trailer in any case", () => {
    expect(attributionProblems("Fix it\n\nCo-Authored-By: Someone <a@b.c>\n")).toHaveLength(1);
    expect(attributionProblems("Fix it\n\nco-authored-by: Someone <a@b.c>\n")).toHaveLength(1);
    expect(attributionProblems("Fix it\n\n  CO-AUTHORED-BY: X\n")).toHaveLength(1);
  });

  it.each([
    "Generated with Claude Code",
    "Generated with [Claude Code](https://claude.com/claude-code)",
    "generated by GitHub Copilot",
    "Generated by ChatGPT",
    "Generated with Gemini",
    "Generated with Cursor",
    "Generated by Codex",
    "Generated by AI",
    "Generated with GPT-5",
  ])("rejects a generated-by line: %s", (line) => {
    expect(attributionProblems(`Add a thing\n\n${line}\n`)).toHaveLength(1);
  });

  it("rejects the robot emoji anywhere", () => {
    expect(attributionProblems("Add a thing \u{1F916}")).toHaveLength(1);
  });

  it("does not trip over ordinary words that contain a tool name", () => {
    expect(attributionProblems("Generated by the main seed script\n\nGenerated with the email template")).toEqual([]);
  });

  it("names the line and reports one problem per offending line", () => {
    const problems = attributionProblems("Subject\n\nBody\nCo-Authored-By: X\nGenerated with Claude Code \u{1F916}\n");
    expect(problems).toHaveLength(2);
    expect(problems[0]).toMatch(/line 4/);
    expect(problems[1]).toMatch(/line 5/);
  });

  it("ignores git comment lines and everything below the scissors line", () => {
    const message = [
      "Add a thing",
      "# Co-Authored-By: this is a comment",
      "# ------------------------ >8 ------------------------",
      "diff --git a/x b/x",
      "+Co-Authored-By: inside the diff",
    ].join("\n");
    expect(attributionProblems(message)).toEqual([]);
  });

  it("handles Windows line endings", () => {
    expect(attributionProblems("Fix\r\n\r\nCo-Authored-By: X\r\n")).toHaveLength(1);
  });
});
